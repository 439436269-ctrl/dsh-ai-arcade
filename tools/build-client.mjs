/**
 * build-client.mjs — bundle the browser half.
 *
 * The DSH client module system hands a plugin exactly one browser file and a
 * CommonJS-ish `require` (only for the packages it declared in
 * `dsh.client.inject`), so everything the panel needs has to arrive as a single
 * bundle. This follows the same recipe `dsh-pocket` uses: esbuild bundles
 * `src/client/index.js` to CommonJS with `react` left external, and the result
 * is wrapped in the `window.__ModuleLoader__.load()` envelope DSH expects.
 *
 * Run with `node tools/build-client.mjs` (or `pnpm build:client`).
 */

import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const outputPath = resolve(root, "lib/client.js");

const result = await build({
	entryPoints: [resolve(root, "src/client/index.js")],
	bundle: true,
	format: "cjs",
	platform: "browser",
	target: ["chrome100"],
	// `react` is provided by the factory's `require`; keeping it external is what
	// makes the bundle small and keeps one React instance in the page.
	external: ["react", "@deepseek-ai/dsh-client-ui-slots"],
	// 同 build-play：保持中文原样，别转义成 \uXXXX。
	charset: "utf8",
	write: false,
	minify: false,
	legalComments: "none",
});

const bundled = result.outputFiles?.[0]?.text;
if (typeof bundled !== "string" || bundled === "") throw new Error("esbuild produced no client bundle");

const wrapped = `/* generated by tools/build-client.mjs — edit src/client/ instead */
window.__ModuleLoader__.load({
	id: "dsh-ai-arcade",
	factory: (require) => {
		var module = { exports: {} };
		var exports = module.exports;
		var React = require("react");
${bundled}
		return module.exports;
	}
});
`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, wrapped, "utf8");
console.log(`wrote ${outputPath} (${wrapped.length} bytes)`);
